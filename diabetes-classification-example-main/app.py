def create_gauge_chart(probability):
    fig = go.Figure(go.Indicator(
        mode="gauge+number",
        value=probability,
        domain={'x': [0, 1], 'y': [0, 1]},
        title={'text': "Risk Probability", 'font': {'size': 16, 'color': '#6B7280'}},
        number={'font': {'size': 40, 'color': '#1F2937'}, 'suffix': '%'},
        gauge={
            'axis': {'range': [None, 100], 'tickwidth': 1, 'tickcolor': "#9CA3AF"},
            'bar': {'color': "#0F52BA"},
            'bgcolor': "white",
            'borderwidth': 2,
            'bordercolor': "#E5E7EB",
            'steps': [
                {'range': [0, 30], 'color': '#D1FAE5'},
                {'range': [30, 60], 'color': '#FEF3C7'},
                {'range': [60, 100], 'color': '#FEE2E2'}
            ],
            'threshold': {'line': {'color': "#EF4444", 'width': 4}, 'thickness': 0.75, 'value': 50}
        }
    ))
    fig.update_layout(paper_bgcolor='rgba(0,0,0,0)', plot_bgcolor='rgba(0,0,0,0)', 
                     font={'family': 'Inter'}, height=250, margin=dict(l=20, r=20, t=30, b=20))
    return fig

def create_feature_chart():
    features = ['Glucose', 'BMI', 'Age', 'BP', 'Insulin', 'Pedigree']
    importance = [0.28, 0.22, 0.18, 0.14, 0.10, 0.08]
    fig = go.Figure(go.Bar(
        x=importance, y=features, orientation='h',
        marker=dict(color=importance, colorscale='Blues', showscale=False),
        text=[f'{val:.0%}' for val in importance], textposition='auto',
    ))
    fig.update_layout(
        title="Impact Factors",
        paper_bgcolor='rgba(0,0,0,0)', plot_bgcolor='rgba(0,0,0,0)',
        font={'family': 'Inter', 'color': '#1F2937'},
        xaxis={'showgrid': False, 'visible': False},
        yaxis={'showgrid': False},
        height=300, margin=dict(l=10, r=10, t=40, b=10)
    )
    return fig


